function storedLang() {
  try { return localStorage.getItem('orbit-lang'); } catch { return null; }
}

let currentLang = storedLang() === 'en' ? 'en' : 'ar';
const listeners = [];

export function getLang() { return currentLang; }

export function onLangChange(fn) { listeners.push(fn); }

export function setLang(lang) {
  if (!translations[lang]) return;
  currentLang = lang;
  try { localStorage.setItem('orbit-lang', lang); } catch { /* private mode */ }
  document.documentElement.lang = lang;
  document.documentElement.dir = lang === 'ar' ? 'rtl' : 'ltr';
  updateDOMTranslations();
  listeners.forEach(fn => fn(lang));
}

export function t(key) {
  return translations[currentLang][key] ?? translations.en[key] ?? key;
}

export function updateDOMTranslations() {
  document.querySelectorAll('[data-i18n]').forEach(el => {
    const val = translations[currentLang][el.getAttribute('data-i18n')];
    if (val) el.textContent = val;
  });
  document.querySelectorAll('[data-i18n-html]').forEach(el => {
    const val = translations[currentLang][el.getAttribute('data-i18n-html')];
    if (val) el.innerHTML = val.replace(/\n/g, '<br/>');
  });
  document.querySelectorAll('[data-i18n-aria]').forEach(el => {
    const val = translations[currentLang][el.getAttribute('data-i18n-aria')];
    if (val) el.setAttribute('aria-label', val);
  });
}
